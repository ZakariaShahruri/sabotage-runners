# Tilemap creation logic
def create_map(tilemap):
    game_objects = []

    for y, row in enumerate(tilemap):
        for x, tile in enumerate(row):
            if tile == 'W':
                #Create a wall
                game_objects.append((wall, x * tilesize, y * tilesize))

            elif tile == '.':
                 game_objects.append((air, x * tilesize, y * tilesize))

    return game_objects

