def draw_map(tilemap, image, screen):
    walls = []

    for y, row in enumerate(tilemap):
        for x, tile in enumerate(row):
            if tile == 'W':
                wall = State(x * tilesize, y * tilesize, image, size=tilesize, is_collidable=True)
                walls.append(wall)

                wall.render(screen)
    
    return walls